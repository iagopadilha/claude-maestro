#!/usr/bin/env python3
"""Free inventory of the code of a folder: sizes, entry points and giant files (no AI, no network).

Usage:
  python code_inventory.py <folder> [--json] [--giant-lines N] [--giant-kb N] [--changed a,b] [--root R] [--name N] [--out F] [--no-write]
  python harness.py inventory <folder> [same options]

  <folder>        folder to walk (the repository root of a single project, or one subproject of a monorepo)
  --root R        project root that holds `.specs/` (default: the nearest parent of <folder> with a `.specs` folder, else <folder>);
                  every path in the result is relative to it
  --name N        inventory name (default `_root` when <folder> is the root, else the relative path with `/` replaced by `-`)
  --giant-lines N a file above N lines is giant (default 1500)
  --giant-kb N    a file above N KB is giant, the fallback for files with few very long lines (default 200)
  --changed a,b   measure ONLY these paths (files or folders; relative to the root, then to <folder>); never writes the file
                  unless --out is given (fast check of what a feature touched)
  --json          print the whole document as JSON (default: a short summary)
  --out F         write the document to F instead of the default place
  --no-write      do not write the file

Default file: `<root>/.specs/project/loop/internal/inventory/<name>.json` (gitignored, outside the map snapshot), written
atomically, and only when `<root>/.specs` exists (a folder without it is not polluted). Document:
  {folder, generated_at, totals:{files, lines, bytes}, by_extension:{".cs":{files, lines, bytes}},
   entry_points:[{path, kind}], giant:[{path, lines, bytes, hint:[up to 5 signatures]}], thresholds:{lines, kb, bytes}}
Ignored at any depth: node_modules, bin, obj, dist, build, .git, vendor, packages, .vs, .next, coverage, __pycache__, hidden
folders; `*.Designer.cs`, `*.g.cs`, `*.generated.*`, `*.min.js`, `*.d.ts`, lock files and files whose header says auto-generated.
Entry point kinds: startup, controller, route, page, solution, compose.
"""
import argparse
import datetime
import json
import os
import re
import sys
import tempfile

ENGINE_DIR = os.path.dirname(os.path.abspath(__file__))
if ENGINE_DIR not in sys.path:
    sys.path.insert(0, ENGINE_DIR)
from classify_structure import SKIP_DIR_NAMES  # noqa: E402
from scale import CODE_EXT  # noqa: E402

DEFAULT_GIANT_LINES = 1500
DEFAULT_GIANT_KB = 200
ROOT_NAME = "_root"
INVENTORY_RELATIVE_DIR = os.path.join(".specs", "project", "loop", "internal", "inventory")
IGNORED_FOLDERS = SKIP_DIR_NAMES | {"vendor", "packages"}
GENERATED_FILE = re.compile(r"(\.designer\.cs|\.g\.cs|\.g\.i\.cs|\.generated\.[^.]+|\.min\.js|\.min\.css|\.d\.ts)$", re.IGNORECASE)
LOCK_FILES = {"package-lock.json", "yarn.lock", "pnpm-lock.yaml", "composer.lock", "poetry.lock", "gemfile.lock", "cargo.lock", "go.sum"}
GENERATED_HEADER = re.compile(rb"auto-generated|autogenerated|<auto-generated", re.IGNORECASE)
HEADER_BYTES = 1024
CHUNK_BYTES = 1024 * 1024
HINT_SCAN_BYTES = 4 * 1024 * 1024
HINT_LIMIT = 5
SHALLOW_ENTRY_DEPTH = 2
STYLE_EXTENSIONS = {".css", ".scss"}
SHALLOW_ENTRY_NAMES = ("main", "index", "app", "server")
SIGNATURE = re.compile(
    r"^[ \t]*(?:export[ \t]+|public[ \t]+|private[ \t]+|protected[ \t]+|internal[ \t]+|static[ \t]+|abstract[ \t]+|sealed[ \t]+|partial[ \t]+|default[ \t]+)*"
    r"(?:(?P<type>class|interface|struct|record|enum|trait)[ \t]+(?P<type_name>[A-Za-z_]\w*)"
    r"|(?:async[ \t]+)?(?:function\*?|def|func|fun)[ \t]+(?P<function_name>[A-Za-z_]\w*)[ \t]*[(<]"
    r"|(?:(?:static|async|virtual|override|abstract|sealed|extern|unsafe)[ \t]+)*[\w<>\[\],.?]+[ \t]+(?P<method_name>[A-Za-z_]\w*)[ \t]*\([^;{}]*\)[ \t]*(?:\{|=>|\r?$))",
    re.MULTILINE)
METHOD_KEYWORDS = {"if", "for", "while", "switch", "catch", "return", "using", "lock", "foreach", "else", "new", "throw", "await"}


def find_root(folder):
    current = os.path.abspath(folder)
    while True:
        if os.path.isdir(os.path.join(current, ".specs")):
            return current
        parent = os.path.dirname(current)
        if parent == current:
            return os.path.abspath(folder)
        current = parent


def relative_to(root, path):
    return os.path.relpath(path, root).replace("\\", "/")


def is_ignored_file(name):
    return bool(GENERATED_FILE.search(name)) or name.lower() in LOCK_FILES


def is_ignored_folder(name):
    return name in IGNORED_FOLDERS or name.startswith(".")


def walk_files(folder):
    for current, dirs, names in os.walk(folder):
        dirs[:] = sorted(name for name in dirs if not is_ignored_folder(name))
        for name in sorted(names):
            if not is_ignored_file(name):
                yield os.path.join(current, name)


def measure_file(path):
    """(lines, bytes, generated) of a file; None when unreadable. Lines = newline count + 1 for an unterminated last line."""
    try:
        with open(path, "rb") as handle:
            head = handle.read(CHUNK_BYTES)
            generated = bool(GENERATED_HEADER.search(head[:HEADER_BYTES]))
            size, lines, last = 0, 0, b""
            chunk = head
            while chunk:
                size += len(chunk)
                lines += chunk.count(b"\n")
                last = chunk[-1:]
                chunk = handle.read(CHUNK_BYTES)
        return (lines + (1 if last and last != b"\n" else 0)), size, generated
    except OSError:
        return None


def entry_point_kind(path_from_folder, absolute_path):
    """The kind of an entry point by name and shape, or None."""
    parts = path_from_folder.replace("\\", "/").split("/")
    name = parts[-1]
    lower = name.lower()
    stem, extension = os.path.splitext(lower)
    if extension in (".sln", ".slnx"):
        return "solution"
    if lower.startswith("docker-compose") and extension in (".yml", ".yaml"):
        return "compose"
    if lower == "package.json":
        try:
            with open(absolute_path, encoding="utf-8-sig") as handle:
                package = json.load(handle)
            return "startup" if isinstance(package, dict) and (package.get("main") or package.get("scripts")) else None
        except (OSError, ValueError):
            return None
    if extension not in CODE_EXT:
        return None
    if lower in ("program.cs", "startup.cs"):
        return "startup"
    if lower.endswith("controller.cs") or stem.endswith(".controller"):
        return "controller"
    if stem.startswith("routes") or stem.endswith(".routes"):
        return "route"
    if stem == "index" and "pages" in [part.lower() for part in parts[:-1]]:
        return "page"
    if stem in SHALLOW_ENTRY_NAMES and extension not in STYLE_EXTENSIONS and len(parts) - 1 <= SHALLOW_ENTRY_DEPTH:
        return "startup"
    return None


def signatures_of(path):
    """Up to 5 class or method signatures (names only) of a code file, in file order."""
    try:
        with open(path, "rb") as handle:
            text = handle.read(HINT_SCAN_BYTES).decode("utf-8", errors="replace")
    except OSError:
        return []
    found = []
    for match in SIGNATURE.finditer(text):
        if match.group("type_name"):
            label = "%s %s" % (match.group("type"), match.group("type_name"))
        else:
            name = match.group("function_name") or match.group("method_name")
            if name in METHOD_KEYWORDS:
                continue
            label = name + "("
        if label not in found:
            found.append(label)
        if len(found) >= HINT_LIMIT:
            break
    return found


def changed_files(root, folder, changed):
    files = []
    for item in changed:
        item = item.strip()
        if not item:
            continue
        candidates = [item] if os.path.isabs(item) else [os.path.join(root, item), os.path.join(folder, item)]
        for candidate in candidates:
            if os.path.isdir(candidate):
                files += list(walk_files(candidate))
                break
            if os.path.isfile(candidate):
                if not is_ignored_file(os.path.basename(candidate)) and not any(
                        is_ignored_folder(part) for part in relative_to(root, candidate).split("/")[:-1]):
                    files.append(os.path.abspath(candidate))
                break
    return sorted(set(files))


def build_inventory(folder, root, giant_lines=DEFAULT_GIANT_LINES, giant_kb=DEFAULT_GIANT_KB, changed=None):
    folder, root = os.path.abspath(folder), os.path.abspath(root)
    files = changed_files(root, folder, changed) if changed else list(walk_files(folder))
    totals = {"files": 0, "lines": 0, "bytes": 0}
    by_extension, entry_points, giants = {}, [], []
    giant_bytes = giant_kb * 1024
    for path in files:
        relative = relative_to(root, path)
        kind = entry_point_kind(relative_to(folder, path) if not changed else relative, path)
        if kind:
            entry_points.append({"path": relative, "kind": kind})
        extension = os.path.splitext(path)[1].lower()
        if extension not in CODE_EXT:
            continue
        measured = measure_file(path)
        if measured is None or measured[2]:
            continue
        lines, size, _ = measured
        totals["files"] += 1
        totals["lines"] += lines
        totals["bytes"] += size
        bucket = by_extension.setdefault(extension, {"files": 0, "lines": 0, "bytes": 0})
        bucket["files"] += 1
        bucket["lines"] += lines
        bucket["bytes"] += size
        if lines > giant_lines or size > giant_bytes:
            giants.append({"path": relative, "lines": lines, "bytes": size, "hint": signatures_of(path)})
    giants.sort(key=lambda item: (-item["lines"], item["path"]))
    return {"folder": relative_to(root, folder) if folder != root else ".",
            "generated_at": datetime.datetime.now().isoformat(timespec="seconds"),
            "totals": totals, "by_extension": dict(sorted(by_extension.items())),
            "entry_points": sorted(entry_points, key=lambda item: item["path"]), "giant": giants,
            "thresholds": {"lines": giant_lines, "kb": giant_kb, "bytes": giant_bytes}}


def default_name(folder, root):
    if os.path.abspath(folder) == os.path.abspath(root):
        return ROOT_NAME
    return relative_to(root, os.path.abspath(folder)).replace("/", "-")


def inventory_path(root, name):
    return os.path.join(root, INVENTORY_RELATIVE_DIR, name + ".json")


def write_atomically(path, document):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    handle, temporary = tempfile.mkstemp(prefix=".inventory-", suffix=".tmp", dir=os.path.dirname(path))
    try:
        with os.fdopen(handle, "w", encoding="utf-8", newline="\n") as stream:
            json.dump(document, stream, ensure_ascii=False, indent=2)
            stream.write("\n")
        os.replace(temporary, path)
    except OSError:
        try:
            os.unlink(temporary)
        except OSError:
            pass
        raise


def build_parser():
    parser = argparse.ArgumentParser(prog="code_inventory", description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("folder")
    parser.add_argument("--json", action="store_true")
    parser.add_argument("--giant-lines", type=int, default=DEFAULT_GIANT_LINES)
    parser.add_argument("--giant-kb", type=int, default=DEFAULT_GIANT_KB)
    parser.add_argument("--changed", default="")
    parser.add_argument("--root")
    parser.add_argument("--name")
    parser.add_argument("--out")
    parser.add_argument("--no-write", action="store_true")
    return parser


def main(argv=None):
    arguments = build_parser().parse_args(argv)
    folder = os.path.abspath(arguments.folder)
    if not os.path.isdir(folder):
        print("not a folder: " + folder, file=sys.stderr)
        return 2
    root = os.path.abspath(arguments.root) if arguments.root else find_root(folder)
    changed = [item for item in arguments.changed.split(",") if item.strip()]
    document = build_inventory(folder, root, arguments.giant_lines, arguments.giant_kb, changed or None)
    target = None
    if not arguments.no_write:
        if arguments.out:
            target = os.path.abspath(arguments.out)
        elif not changed and os.path.isdir(os.path.join(root, ".specs")):
            target = inventory_path(root, arguments.name or default_name(folder, root))
    written = ""
    if target:
        try:
            write_atomically(target, document)
            written = target
        except OSError as error:
            print("could not write %s: %s" % (target, error), file=sys.stderr)
    if arguments.json:
        print(json.dumps(document, ensure_ascii=False, indent=2))
    else:
        totals = document["totals"]
        print("inventory: %d files, %d giant (%d lines, %d KB)" % (totals["files"], len(document["giant"]), totals["lines"], totals["bytes"] // 1024))
        for item in document["giant"]:
            print("  giant: %s (%d lines, %d KB) %s" % (item["path"], item["lines"], item["bytes"] // 1024, ", ".join(item["hint"])))
        print("  entry points: %d" % len(document["entry_points"]))
        if written:
            print("  written: " + written)
    return 0


if __name__ == "__main__":
    sys.exit(main())
