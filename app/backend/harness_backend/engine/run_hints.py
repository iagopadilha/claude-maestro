#!/usr/bin/env python3
"""`How to run` block of a project's CLAUDE.md: the commands to run the app locally, read from the project itself.

Deterministic (no AI): the block between RUN:BEGIN and RUN:END is generated from `Properties/launchSettings.json` (.NET)
and `package.json` / `vite.config.*` (front ends), and rewritten on every call. Nothing outside the markers is touched.
Standard: always run with HTTPS first (the `https` launch profile for .NET); HTTP only when HTTPS does not answer.

    python run_hints.py <root>            # prints the block
    python run_hints.py <root> --write    # writes it into <root>/CLAUDE.md
"""
import datetime
import json
import os
import re
import sys

BEGIN = "<!-- RUN:BEGIN -->"
END = "<!-- RUN:END -->"
SKIPPED_DIRS = {"node_modules", ".git", "bin", "obj", "dist", "build", ".specs", ".next", "__pycache__"}
MAX_DEPTH = 4
HTTPS_PROFILE = "https"
RUN_LINE_PATTERN = re.compile(r"^\s*(?:[-*]\s*)?`?dotnet run\b.*$", re.M)
VITE_PORT_PATTERN = re.compile(r"\bport\s*:\s*(\d+)")
VITE_HTTPS_PATTERN = re.compile(r"\bhttps\s*:\s*(?!false)\S")
FRONT_SCRIPTS = ("dev", "start:dev", "start")
TEXT_ENCODING = "utf-8"


def walk_files(root, names):
    """{name: [path]} of the files called `names`, up to MAX_DEPTH folders down, skipping build/dependency folders."""
    found = {name: [] for name in names}
    root = os.path.abspath(root)
    base_depth = root.rstrip(os.sep).count(os.sep)
    for folder, subdirs, files in os.walk(root):
        subdirs[:] = sorted(d for d in subdirs if d not in SKIPPED_DIRS)
        if folder.rstrip(os.sep).count(os.sep) - base_depth >= MAX_DEPTH:
            subdirs[:] = []
        for name in files:
            if name in found:
                found[name].append(os.path.join(folder, name))
    return found


def read_json(path):
    try:
        with open(path, encoding=TEXT_ENCODING) as handle:
            return json.load(handle)
    except (OSError, ValueError):
        return None


def read_text(path):
    try:
        with open(path, encoding=TEXT_ENCODING, errors="replace") as handle:
            return handle.read()
    except OSError:
        return ""


def relative(root, path):
    value = os.path.relpath(path, root).replace(os.sep, "/")
    return "." if value == "." else value


def dotnet_entries(root):
    """One entry per launchSettings.json that sits next to a .csproj: {"dir", "has_https", "urls"}; `*.Api` first."""
    entries = []
    for path in walk_files(root, ("launchSettings.json",))["launchSettings.json"]:
        project_dir = os.path.dirname(os.path.dirname(path))
        if not any(name.endswith(".csproj") for name in os.listdir(project_dir)):
            continue
        profiles = (read_json(path) or {}).get("profiles") or {}
        https = profiles.get(HTTPS_PROFILE) or {}
        entries.append({"dir": relative(root, project_dir), "has_https": bool(https),
                        "urls": str(https.get("applicationUrl") or "").replace(";", " , ")})
    entries.sort(key=lambda entry: (not entry["dir"].endswith(".Api"), entry["dir"]))
    return entries


def front_entries(root):
    """One entry per package.json with a dev script: {"dir", "script", "port", "https"} (port/https from the vite config)."""
    entries = []
    for path in walk_files(root, ("package.json",))["package.json"]:
        scripts = (read_json(path) or {}).get("scripts") or {}
        script = next((name for name in FRONT_SCRIPTS if name in scripts), None)
        if not script:
            continue
        project_dir = os.path.dirname(path)
        config = "".join(read_text(os.path.join(project_dir, name))
                         for name in sorted(os.listdir(project_dir)) if name.startswith("vite.config."))
        port = VITE_PORT_PATTERN.search(config)
        entries.append({"dir": relative(root, project_dir), "script": script, "port": port.group(1) if port else None,
                        "https": bool(VITE_HTTPS_PATTERN.search(config))})
    return entries


def where(entry):
    return "" if entry["dir"] == "." else " (in `%s`)" % entry["dir"]


def build_block(root):
    """The block text (with markers), or None when the folder has neither a .NET launchSettings nor a front end."""
    back, front = dotnet_entries(root), front_entries(root)
    if not back and not front:
        return None
    lines = [BEGIN, "## How to run (generated by the harness app: rewritten on every update, do not edit inside the markers)",
             "Always run with HTTPS first. Use HTTP only when the host or port does not answer over HTTPS.", ""]
    for entry in back:
        if entry["has_https"]:
            lines.append("- .NET back end: `dotnet run --project %s --launch-profile %s`%s"
                         % (entry["dir"], HTTPS_PROFILE, " -> " + entry["urls"] if entry["urls"] else ""))
        else:
            lines.append("- .NET back end `%s`: **no `%s` profile in `Properties/launchSettings.json`**; add one with an "
                         "`https://localhost:<port>` applicationUrl before running (HTTP-only is the fallback, not the standard)."
                         % (entry["dir"], HTTPS_PROFILE))
    if back:
        lines.append("  - Untrusted dev certificate: `dotnet dev-certs https --trust` is the user's action; the agents only warn.")
    for entry in front:
        scheme = "https (set in the vite config)" if entry["https"] else "http on localhost unless the project serves https"
        port = ", port %s" % entry["port"] if entry["port"] else ""
        lines.append("- Front end%s: `npm run %s`%s, %s" % (where(entry), entry["script"], port, scheme))
    lines += ["", "If a command above disagrees with another line of this file, this block wins.", END, ""]
    return "\n".join(lines)


def conflicting_lines(text):
    """`dotnet run` lines written outside the generated block that do not use the https profile."""
    outside = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), "", text or "", flags=re.S)
    return [match.group(0).strip() for match in RUN_LINE_PATTERN.finditer(outside) if "--launch-profile" not in match.group(0)]


def write_block(root):
    """Writes (or rewrites) the block in <root>/CLAUDE.md; returns (changed, conflicting_lines). No block = nothing written."""
    block = build_block(root)
    path = os.path.join(root, "CLAUDE.md")
    text = read_text(path) if os.path.exists(path) else None
    conflicts = conflicting_lines(text)
    if block is None:
        return False, conflicts
    if text is None:
        text = "# " + os.path.basename(os.path.abspath(root)) + "\n\n"
    if BEGIN in text:
        updated = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n?", lambda _: block, text, count=1, flags=re.S)
    else:
        updated = text.rstrip("\n") + "\n\n" + block
    if updated == text:
        return False, conflicts
    with open(path, "w", encoding=TEXT_ENCODING, newline="\n") as handle:
        handle.write(updated)
    return True, conflicts


CODEBASE_BEGIN = "<!-- CODEBASE:BEGIN -->"
CODEBASE_END = "<!-- CODEBASE:END -->"
CODEBASE_PURPOSE = {
    "STACK.md": "languages, frameworks, versions and main dependencies",
    "ARCHITECTURE.md": "layers, patterns and how data flows",
    "CONVENTIONS.md": "naming, code style and error handling in use",
    "STRUCTURE.md": "folder layout and where each kind of code lives",
    "TESTING.md": "how tests are written and run",
    "INTEGRATIONS.md": "external APIs, databases, queues and authentication",
    "CONCERNS.md": "tech debt, risks and fragile areas",
    "SYSTEM.md": "how the subprojects of this monorepo talk to each other (routes, contracts, flows)",
}
SYSTEM_DOCUMENT_NAME = "SYSTEM.md"  # the only document of the root `docs/codebase` of a confirmed monorepo (never "the map")


MAP_FOLDER = "docs/codebase"  # where the map is written: the project root, versioned with the code, reused by the team
LEGACY_MAP_FOLDER = ".specs/codebase"  # older projects: still read when MAP_FOLDER has no document
MAP_INDEX_NAME = "README.md"  # written by the app (not by the AI): the index and the "mapped at" marker
MAPPED_AT_PATTERN = re.compile(r"^Mapped at commit (\S+) on (\S+)", re.M)


def list_map_documents(folder):
    """Names of the map documents (`.md`, top level) in `folder`, without the app's own index. [] when the folder is missing."""
    try:
        names = os.listdir(folder)
    except OSError:
        return []
    return sorted(name for name in names if name.lower().endswith(".md") and name != MAP_INDEX_NAME
                  and os.path.isfile(os.path.join(folder, name)))


def is_confirmed_monorepo_root(root):
    """True when `root` is the root of a confirmed monorepo (its `docs/codebase` then holds only `SYSTEM.md`). Never raises."""
    if not root:
        return False
    try:
        import subprojects  # lazy: the engine folder is on sys.path whenever this module was imported from it
        return bool(subprojects.monorepo_confirmed(root))
    except Exception:
        return False


def list_root_map_documents(root, relative=MAP_FOLDER):
    """Map documents of `<root>/<relative>` for the "is the project mapped" questions: in a confirmed monorepo the root
    `docs/codebase` is not a project map (it holds only `SYSTEM.md` and the index), so nothing is listed there."""
    if relative == MAP_FOLDER and is_confirmed_monorepo_root(root):
        return []
    return list_map_documents(os.path.join(root, *relative.split("/")))


def find_map_folder(*roots):
    """Relative folder (`docs/codebase`, else the legacy `.specs/codebase`) that holds the map and the root it was found under:
    (relative, root). Nothing found = (MAP_FOLDER, first root). `docs/codebase` is always read first. The root `docs/codebase` of a
    confirmed monorepo is skipped: it holds only `SYSTEM.md`, which never counts as the project's map."""
    for relative in (MAP_FOLDER, LEGACY_MAP_FOLDER):
        for root in roots:
            if root and list_root_map_documents(root, relative):
                return relative, root
    return MAP_FOLDER, (roots[0] if roots else "")


def read_mapped_commit(folder):
    """Short sha written in the index (`Mapped at commit <sha> on <date>`), or None."""
    found = MAPPED_AT_PATTERN.search(read_text(os.path.join(folder, MAP_INDEX_NAME)))
    return found.group(1) if found and found.group(1) != "unknown" else None


def build_map_index(names, commit, today):
    """Text of `docs/codebase/README.md`: what each document is for and when the map was made."""
    lines = ["# Codebase map", "",
             "Short documents about what this code already is, generated by the Loop Harness so the team and the AI can reuse them.",
             "They are a guide, NOT the source of truth: when a document and the code disagree, the code wins.",
             "Read one only when the task needs it. If a change really alters one of them, update it in the same change.", ""]
    for name in names:
        lines.append("- [%s](%s): %s" % (name, name, CODEBASE_PURPOSE.get(name, "mapping document")))
    lines += ["", "Mapped at commit %s on %s" % (commit or "unknown", today), ""]
    return "\n".join(lines)


def write_map_index(root, commit=None, today=None):
    """Creates or updates `<root>/docs/codebase/README.md` (idempotent). True when the file changed. No documents = nothing."""
    folder = os.path.join(root, *MAP_FOLDER.split("/"))
    names = list_map_documents(folder)
    if not names:
        return False
    text = build_map_index(names, commit, today or datetime.date.today().isoformat())
    path = os.path.join(folder, MAP_INDEX_NAME)
    if os.path.exists(path) and read_text(path) == text:
        return False
    with open(path, "w", encoding=TEXT_ENCODING, newline="\n") as handle:
        handle.write(text)
    return True


def build_codebase_block(root):
    """The `Codebase map` block (with markers) pointing at the map (`docs/codebase`, or the legacy `.specs/codebase`), or None."""
    relative, found_root = find_map_folder(root)
    names = list_root_map_documents(found_root, relative)
    if not names:
        return None
    lines = [CODEBASE_BEGIN, "## Codebase map (generated by the harness app: rewritten when the map is made again)",
             "Short documents about what the code already is, in `%s/`. Read one ONLY WHEN the task needs it "
             "(stack, architecture, structure, conventions, tests, integrations, risks), not at the start of every session:" % relative, ""]
    for name in names:
        lines.append("- `%s/%s`: %s" % (relative, name, CODEBASE_PURPOSE.get(name, "mapping document")))
    lines += ["", "They are a guide, not the source of truth: if a document disagrees with the code, the code wins. "
              "If a change really alters one of them, update the document in the same change.", CODEBASE_END, ""]
    return "\n".join(lines)


def remove_codebase_block_from_file(path):
    """Removes the `CODEBASE` block from the CLAUDE.md at `path`; True when the file changed."""
    import context_block
    try:
        with open(path, encoding=TEXT_ENCODING, newline="") as handle:  # newline="": read the file's own line endings
            text = handle.read()
    except (OSError, UnicodeError):
        return False
    updated, removed = context_block.remove_codebase_blocks(text)
    if not removed:
        return False
    with open(path, "w", encoding=TEXT_ENCODING, newline="") as handle:  # newline="": the file's own line endings stay
        handle.write(updated)
    return True


def write_codebase_block(root):
    """Writes (or rewrites) the Codebase map block in <root>/CLAUDE.md; True when the file changed. No documents = nothing.
    A CLAUDE.md that has the `maestro:context` block already lists the map there (one block about the map per file): the
    `CODEBASE` block is then not written and an existing one is removed."""
    path = os.path.join(root, "CLAUDE.md")
    if os.path.exists(path):
        import context_block  # lazy, like `subprojects`: the engine folder is on sys.path whenever this module was imported
        existing = read_text(path)
        if context_block.START_MARKER in existing:
            return remove_codebase_block_from_file(path)
    block = build_codebase_block(root)
    if block is None:
        return False
    text = read_text(path) if os.path.exists(path) else "# " + os.path.basename(os.path.abspath(root)) + "\n\n"
    if CODEBASE_BEGIN in text:
        updated = re.sub(re.escape(CODEBASE_BEGIN) + r".*?" + re.escape(CODEBASE_END) + r"\n?", lambda _: block, text, count=1, flags=re.S)
    else:
        updated = text.rstrip("\n") + "\n\n" + block
    if updated == text:
        return False
    with open(path, "w", encoding=TEXT_ENCODING, newline="\n") as handle:
        handle.write(updated)
    return True


def main(argv):
    if not argv or argv[0] in ("-h", "--help"):
        print(__doc__)
        return 2
    root = os.path.abspath(argv[0])
    if "--write" in argv[1:]:
        changed, conflicts = write_block(root)
        print("CLAUDE.md %s" % ("updated" if changed else "unchanged"))
        for line in conflicts:
            print("warning: run line without the https profile: %s" % line)
        return 0
    print(build_block(root) or "nothing to run found")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
