"""Creates the demo project (a real git repo with a full `.specs/`) and plays the turns that already happened, instantly.
Also resets the story (for `--loop`): back to the scaffold commit and the same seeded turns.
"""
import datetime
import os
import sys

from ..repositories.loop_file_repository import loop_state
from .demo_story_catalog import (FEATURES, GOAL, LOOP_BRANCH, MAX_COST_USD, PERMISSIONS, PROJECT_NAME, PROJECT_TEXT, RULES_TEXT,
                                 SCAFFOLD_BRANCH, SCAFFOLD_FOLDERS, SEEDED_ANSWER, SEEDED_TURNS, STATE_HEADER, TURN_TIMEOUT_MINUTES,
                                 VALIDATE_LINES, WAVE, build_turn_plans)
from .demo_story_player import DemoStoryPlayer, build_initial_meta, render_roadmap, to_local_iso
from .demo_workspace import DemoGitRepository, remove_file, remove_tree, write_json_atomically, write_text_atomically

STUBS_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "stubs")
ENGINE_STUB_PATH = os.path.join(STUBS_DIR, "demo_engine_stub.py")
CLAUDE_STUB_PATH = os.path.join(STUBS_DIR, "demo_claude_stub.py")
STORY_LENGTH_BEFORE_NOW = datetime.timedelta(minutes=60)  # virtual time of the whole story ends around the real "now"
CLAUDE_TEXT = """# acme-checkout

Card checkout for the Acme store (demo project of Loop Harness).

Conformance: STANDARD

@.specs/project/RULES.md
"""
README_TEXT = "# acme-checkout\n\n" + GOAL + "\n\nDemo project generated by `harness.py demo`.\n"
ARCHITECTURE_TEXT = """# Architecture

- `services/*`: one Python service per bounded context, each with its own tests.
- `web/*`: React apps; shared components live in `web/shared/`.
- `infra/rate-limiter`: edge limits; `infra/prod/`: production values, applied by the platform team only.
- `migrations/`: reviewed SQL migrations.
"""
LOOP_STATE_ENTRIES = ("json/LOOP.json", "json/meta.json", "internal/turns", "internal/snapshots", "internal/guard.log",
                      "internal/LOOP.lock", "internal/demo-answer.txt", "ANSWERS.md", "VALIDATE.md", "GRAPH.md")


def build_loop_command(repo_dir):
    """LOOP-CMD.json of the demo: the panel's answer/resume relaunch the engine STUB (it only records the answer), never run_loop."""
    return {"argv": [sys.executable, ENGINE_STUB_PATH, repo_dir, "--wave", str(WAVE), "--max-cost", str(MAX_COST_USD),
                     "--timeout", str(TURN_TIMEOUT_MINUTES)], "cwd": repo_dir}


class DemoProjectSeeder:
    def __init__(self, workspace, clock=None):
        self.workspace = workspace
        self.repo_dir = workspace.repo_dir
        self.git = DemoGitRepository(self.repo_dir)
        self.clock = clock or (lambda: datetime.datetime.now(datetime.timezone.utc))
        self.scaffold_head = None
        self.generation = 0

    # ------------------------------------------------ paths
    def project_file(self, *parts):
        return os.path.join(self.repo_dir, ".specs", "project", *parts)

    def repo_file(self, relative):
        return os.path.join(self.repo_dir, *relative.split("/"))

    # ------------------------------------------------ seed
    def seed(self, keeps_lock=False, answer_provider=None):
        """Creates the repo and plays the seeded turns. Returns the player positioned on the first animated step."""
        self.create_repository()
        return self.start_story(keeps_lock, answer_provider)

    def reset_story(self, keeps_lock=False, answer_provider=None):
        """Back to the scaffold commit and a fresh `.specs/` loop state, then the seeded turns again (new session ids)."""
        self.generation += 1
        remove_file(loop_state.loop_path(self.repo_dir, "LOOP.lock"))
        self.git.reset_to(self.scaffold_head)
        for entry in LOOP_STATE_ENTRIES:
            path = os.path.join(loop_state.loop_dir(self.repo_dir), *entry.split("/"))
            if os.path.isdir(path):
                remove_tree(path)
            else:
                remove_file(path)
        remove_tree(os.path.join(self.repo_dir, ".specs", "features"))
        remove_tree(self.project_file("phases"))
        remove_tree(self.workspace.transcripts_dir)
        return self.start_story(keeps_lock, answer_provider)

    def start_story(self, keeps_lock, answer_provider):
        story_start = self.clock() - STORY_LENGTH_BEFORE_NOW
        self.write_specs_baseline(story_start)
        player = DemoStoryPlayer(self.workspace, self.git, build_turn_plans(), story_start, generation=self.generation)
        player.play_until_turn(SEEDED_TURNS)
        write_text_atomically(loop_state.state_file(self.repo_dir, "VALIDATE.md"), "# Validate later\n\n" + "\n".join(VALIDATE_LINES) + "\n")
        player.keeps_lock = keeps_lock
        if answer_provider is not None:
            player.answer_provider = answer_provider
        return player

    def create_repository(self):
        self.git.initialize(SCAFFOLD_BRANCH)
        scaffold = {"README.md": README_TEXT, ".gitignore": ".specs/\n", "CLAUDE.md": CLAUDE_TEXT, "docs/ARCHITECTURE.md": ARCHITECTURE_TEXT,
                    "infra/prod/terraform.tfvars": 'region = "eu-west-1"\nedge_rate_limit = 600\n',
                    "migrations/0006_add_orders.sql": "CREATE TABLE orders (id BIGINT PRIMARY KEY, total_cents BIGINT NOT NULL);\n"}
        for folder in SCAFFOLD_FOLDERS:
            scaffold.setdefault(folder + "/README.md", "# %s\n\nPart of %s.\n" % (folder.rsplit("/", 1)[-1], PROJECT_NAME))
        first = ["README.md", ".gitignore", "CLAUDE.md"] + [path for path in scaffold if path.endswith("/README.md")]
        for relative, text in scaffold.items():
            write_text_atomically(self.repo_file(relative), text)
        self.git.commit_paths(first, "chore: scaffold services, web apps and infra folders")
        self.git.commit_paths([path for path in scaffold if path not in first], "docs: architecture notes, prod values and the orders migration")
        self.git.create_branch(LOOP_BRANCH)
        self.scaffold_head = self.git.get_head()

    def write_specs_baseline(self, story_start):
        """PROJECT, ROADMAP (all pending), STATE, RULES, PERMISSIONS, LOOP-CMD, meta, ANSWERS, the approval and the turn 0 snapshot."""
        features = {feature["slug"]: {"status": "pending", "tries": 0, "commit": None, "note": None} for feature in FEATURES}
        write_text_atomically(self.project_file("PROJECT.md"), PROJECT_TEXT)
        write_text_atomically(self.project_file("ROADMAP.md"), render_roadmap(features))
        write_text_atomically(self.project_file("STATE.md"), STATE_HEADER)
        write_text_atomically(self.project_file("RULES.md"), RULES_TEXT)
        write_json_atomically(loop_state.loop_path(self.repo_dir, "PERMISSIONS.json"), PERMISSIONS)
        write_json_atomically(loop_state.loop_path(self.repo_dir, "LOOP-CMD.json"), build_loop_command(self.repo_dir))
        write_json_atomically(loop_state.loop_path(self.repo_dir, "meta.json"), build_initial_meta(story_start))
        write_text_atomically(loop_state.state_file(self.repo_dir, "ANSWERS.md"),
                              "# Answers\n\n## Answer %s [applied]\nQuestion: %s\nUser answer: %s\n"
                              % (to_local_iso(story_start), SEEDED_ANSWER["question"], SEEDED_ANSWER["answer"]))
        loop_state.approve_roadmap(self.repo_dir, to_local_iso(story_start))
        loop_state.snapshot(self.repo_dir, 0, self.git.get_head())
