"""The generated "What the agents can use" section of `.specs/project/PROJECT.md`, between the markers

    <!-- maestro:capabilities -->  ...  <!-- /maestro:capabilities -->

Server generated (repositories with role, what the agents may read, what they may edit, what is reserved) and rewritten after a
planning reply, a repository change and at approval. Text outside the markers is never touched (byte-identical, line endings
included); a missing block is appended at the end of the file. The planning AI never edits inside the markers (the guard reverts it).
"""
import os

START_MARKER = "<!-- maestro:capabilities -->"
END_MARKER = "<!-- /maestro:capabilities -->"
PROJECT_FILE_PARTS = (".specs", "project", "PROJECT.md")
REPOS_FILE_PARTS = (".specs", "project", "REPOS.json")
ROLE_EDIT, ROLE_REFERENCE = "edit", "reference"
MAP_FOLDER_SUFFIX = "docs/codebase"
SYSTEM_DOCUMENT = "docs/codebase/SYSTEM.md"
TEXT_ENCODING = "utf-8"


def read_available_servers():
    """MCP read servers available on this machine, from `engine/mcp_access.available_servers()`; none when it is missing or fails."""
    try:
        try:
            import mcp_access  # noqa: E402  (engine folder is on sys.path through specs_file_repository)
        except ImportError:
            from ..engine import mcp_access
        return mcp_access.available_servers()
    except Exception:  # noqa: BLE001  (the section only loses the MCP line)
        return []


def describe_servers(servers):
    """['name (tool, tool)'] from a list of names, a list of {server|name, tools} or a {name: tools} dict."""
    lines = []
    if isinstance(servers, dict):
        servers = [{"server": name, "tools": tools} for name, tools in servers.items()]
    for item in servers or []:
        if isinstance(item, str):
            lines.append(item)
        elif isinstance(item, dict) and (item.get("server") or item.get("name")):
            tools = [str(tool) for tool in item.get("tools") or []]
            lines.append("%s (%s)" % (item.get("server") or item.get("name"), ", ".join(tools)) if tools else str(item.get("server") or item.get("name")))
    return lines


def import_subprojects():
    """The engine module `subprojects` (the engine folder is on sys.path through specs_file_repository)."""
    try:
        import subprojects  # noqa: E402
    except ImportError:
        from ..engine import subprojects
    return subprojects


def folder_has_documents(folder):
    try:
        return any(name.lower().endswith(".md") for name in os.listdir(folder))
    except OSError:
        return False


class ProjectCapabilitiesService:
    def __init__(self, specs_file_repository, log, mcp_provider=None):
        """`mcp_provider()` -> the MCP servers the agents may read (tests inject; default: `engine/mcp_access`)."""
        self.specs_file_repository = specs_file_repository
        self.log = log
        self.mcp_provider = mcp_provider or read_available_servers

    # ------------------------------------------------ render
    def read_repositories(self, context):
        """[(name, path, role, primary)] from REPOS.json (role missing = edit; the primary is always edit); the primary alone without file."""
        data = self.specs_file_repository.read_json(os.path.join(context.work_dir, *REPOS_FILE_PARTS))
        primary_key = os.path.normcase(os.path.normpath(context.repo_path))
        repos, found_primary = [], False
        for item in data.get("repos") or []:
            if not isinstance(item, dict) or not item.get("path"):
                continue
            path = str(item["path"])
            primary = bool(item.get("primary")) or os.path.normcase(os.path.normpath(path)) == primary_key
            found_primary = found_primary or primary
            role = ROLE_EDIT if primary or item.get("role") != ROLE_REFERENCE else ROLE_REFERENCE
            repos.append((str(item.get("name") or os.path.basename(os.path.normpath(path))), path, role, primary))
        if not found_primary:
            repos.insert(0, (os.path.basename(os.path.normpath(context.repo_path)), context.repo_path, ROLE_EDIT, True))
        return repos

    def render(self, context):
        """The whole marked block (markers included), without a trailing newline."""
        repos = self.read_repositories(context)
        lines = [START_MARKER, "<!-- Generated by the Loop Harness app: rewritten on every change, do not edit between the markers. -->",
                 "## What the agents can use (inside the loop)", "", "**Repositories**"]
        for name, path, role, primary in repos:
            lines.append("- `%s` (%s%s): %s" % (name, role, ", primary" if primary else "", path.replace("\\", "/")))
        lines += self.render_subprojects(context, repos)
        edit_names = [name for name, _, role, _ in repos if role == ROLE_EDIT]
        servers = describe_servers(self.mcp_provider())
        lines += ["", "**Read** (always allowed)",
                  "- Every git repository on this machine (the repository catalog), read only; the `reference` repositories above are in scope.",
                  "- git read commands (`git log`, `git diff`, `git show`, `git status`, `git blame`).",
                  "- MCP read tools: %s." % ("; ".join(servers) if servers else "none available on this machine"),
                  "", "**Edit**",
                  "- Only the PATHS of your feature, in the loop worktree of an `edit` repository (%s). A `reference` repository is never edited."
                  % (", ".join("`%s`" % name for name in edit_names) or "none"),
                  "", "**Reserved** (do not try: the guard blocks it)",
                  "- `git commit`: the orchestrator's checkpoint, never a subagent.",
                  "- `git push` and the pull request: `harness.py deliver`, once, at the end of the loop.",
                  "- The state files (`.specs/project/loop/`) and `harness.py`: the engine.",
                  "", "A guard block is final: do not retry the same action or look for another way around it; say what you need and stop.",
                  "", "Outside the loop (the user talking to Claude directly, tlc-spec-driven) nothing in this section restricts git or anything else.",
                  END_MARKER]
        return "\n".join(lines)

    def render_subprojects(self, context, repos):
        """The `**Subprojects**` lines of every confirmed monorepo (empty list for a single project, an unconfirmed list or any failure)."""
        try:
            subprojects = import_subprojects()
            stored, _ = subprojects.read_repos(context.work_dir)  # SUBPROJECTS.json always lives under the primary's work folder
            lines = []
            for name, path, _, primary in repos:
                entry = stored.get(name)
                if not (isinstance(entry, dict) and entry.get("monorepo") is True and entry.get("confirmed") is True):
                    continue
                root = context.work_dir if primary else path
                lines += self.render_subprojects_of_repo(subprojects, root, name, entry)
            return (["", "**Subprojects**"] + lines) if lines else []
        except Exception:  # noqa: BLE001  (the section only loses the Subprojects lines)
            return []

    @staticmethod
    def render_subprojects_of_repo(subprojects, root, name, entry):
        lines = []
        for project in subprojects.entry_projects(entry):
            base = subprojects.normalize(project["path"])
            if project.get("skip") is True:
                lines.append("- `%s` `%s`: skipped%s" % (name, base, " (%s)" % project["reason"] if project.get("reason") else ""))
                continue
            map_folder = "%s/%s" % (base, MAP_FOLDER_SUFFIX)
            has_map = folder_has_documents(os.path.join(root, *map_folder.split("/")))
            lines.append("- `%s` `%s`: stack %s, skill %s, Conformance %s, map `%s` (%s), CLAUDE.md `%s/CLAUDE.md`" % (
                name, base, project.get("stack") or "-", project.get("skill") or "-", subprojects.read_conformance(root, base),
                map_folder, "has documents" if has_map else "no documents yet", base))
        system_exists = os.path.isfile(os.path.join(root, *SYSTEM_DOCUMENT.split("/")))
        lines.append("- `%s` system map: `%s` (%s)" % (name, SYSTEM_DOCUMENT, "exists" if system_exists else "does not exist yet"))
        return lines

    # ------------------------------------------------ write
    def write(self, context):
        """Rewrites the marked block of PROJECT.md (appends it when missing). Returns True when the file changed; False when nothing
        changed or there is no PROJECT.md yet (the structure initialization creates it)."""
        path = os.path.join(context.work_dir, *PROJECT_FILE_PARTS)
        try:
            with open(path, encoding=TEXT_ENCODING, newline="") as handle:
                text = handle.read()
        except OSError:
            return False
        block = self.render(context)
        updated = self.replace_block(text, block)
        if updated == text:
            return False
        with open(path, "w", encoding=TEXT_ENCODING, newline="") as handle:
            handle.write(updated)
        self.log.info("project_capabilities_written", project=context.project.id)
        return True

    def after_list_confirmed(self, context, key, folder, entry):
        """Hook for `SubprojectsService.add_after_list_confirmed`: confirming the list rewrites the marked block of PROJECT.md only."""
        self.write(context)

    @staticmethod
    def replace_block(text, block):
        """`text` with the marked block replaced by `block`; appended after a blank line when the markers are not there. Nothing outside
        the markers changes."""
        start = text.find(START_MARKER)
        end = text.find(END_MARKER, start + len(START_MARKER)) if start >= 0 else -1
        if start >= 0 and end >= 0:
            newline = "\r\n" if "\r\n" in text[start:end] else "\n"
            return text[:start] + block.replace("\n", newline) + text[end + len(END_MARKER):]
        newline = "\r\n" if "\r\n" in text else "\n"
        separator = "" if not text else (newline if text.endswith("\n") else newline * 2)  # one blank line before the block
        return text + separator + block.replace("\n", newline) + newline
