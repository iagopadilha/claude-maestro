SCRIPT = os.path.join(engine_env.ENGINE_DIR, "code_inventory.py")


def write(path, text=""):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)


class InventoryTestCase(unittest.TestCase):
    def setUp(self):
        self.root = tempfile.mkdtemp(prefix="inventory-")
        self.addCleanup(shutil.rmtree, self.root, True)
        os.makedirs(os.path.join(self.root, ".specs"))

    def path(self, *parts):
        return os.path.join(self.root, *parts)

    def run_cli(self, *arguments):
        return subprocess.run([sys.executable, SCRIPT] + list(arguments), capture_output=True, text=True, timeout=120)

    def build_world(self):
        legacy = "namespace Shop;\npublic class LegacyDataAccess\n{\n    public int GetOrders(int id)\n    {\n        return 1;\n    }\n}\n"
        write(self.path("Shop.Data", "Legacy.cs"), legacy + "// filler\n" * 20000)
        bundle = "function renderPage(a) { return a; }\nclass Router {}\n" + ("var z = 2; // " + "y" * 90 + "\n") * 3000
        write(self.path("web", "bundle.js"), bundle)
        write(self.path("Shop.Api", "Program.cs"), "var app = 1;\n")
        write(self.path("Shop.Api", "OrdersController.cs"), "public class OrdersController {}\n")
        write(self.path("Shop.sln"))
        write(self.path("bin", "Debug", "Big.cs"), "x\n" * 5000)
        write(self.path("node_modules", "lib", "index.js"), "x\n" * 5000)
        write(self.path("Shop.Data", "Old.Designer.cs"), "x\n" * 5000)
        write(self.path("Shop.Data", "Gen.cs"), "// <auto-generated>\n" + "x\n" * 5000)
        write(self.path("web", "app.min.js"), "x\n" * 5000)
        write(self.path("docker-compose.yml"), "services: {}\n")


class TestInventory(InventoryTestCase):
    def test_giant_files_carry_signatures_and_ignored_folders_are_skipped(self):
        self.build_world()
        document = code_inventory.build_inventory(self.root, self.root)
        giants = {item["path"]: item for item in document["giant"]}
        self.assertEqual(set(giants), {"Shop.Data/Legacy.cs", "web/bundle.js"})
        self.assertEqual(giants["Shop.Data/Legacy.cs"]["lines"], 20008)
        self.assertIn("class LegacyDataAccess", giants["Shop.Data/Legacy.cs"]["hint"])
        self.assertIn("GetOrders(", giants["Shop.Data/Legacy.cs"]["hint"])
        self.assertLessEqual(len(giants["web/bundle.js"]["hint"]), 5)
        self.assertIn("renderPage(", giants["web/bundle.js"]["hint"])
        self.assertGreater(giants["web/bundle.js"]["bytes"], 200 * 1024)
        self.assertEqual(document["totals"]["files"], 4)
        self.assertEqual(set(document["by_extension"]), {".cs", ".js"})

    def test_entry_points_have_a_kind(self):
        self.build_world()
        points = {item["path"]: item["kind"] for item in code_inventory.build_inventory(self.root, self.root)["entry_points"]}
        self.assertEqual(points["Shop.Api/Program.cs"], "startup")
        self.assertEqual(points["Shop.Api/OrdersController.cs"], "controller")
        self.assertEqual(points["Shop.sln"], "solution")
        self.assertEqual(points["docker-compose.yml"], "compose")

    def test_thresholds_come_from_the_arguments(self):
        write(self.path("a.cs"), "x\n" * 50)
        write(self.path("b.cs"), "x\n" * 5)
        document = code_inventory.build_inventory(self.root, self.root, giant_lines=10, giant_kb=200)
        self.assertEqual([item["path"] for item in document["giant"]], ["a.cs"])
        self.assertEqual(document["thresholds"]["lines"], 10)
        by_size = code_inventory.build_inventory(self.root, self.root, giant_lines=1000, giant_kb=0)
        self.assertEqual({item["path"] for item in by_size["giant"]}, {"a.cs", "b.cs"})

    def test_cli_thresholds_and_json(self):
        write(self.path("a.cs"), "x\n" * 50)
        result = self.run_cli(self.root, "--json", "--giant-lines", "10", "--no-write")
        self.assertEqual(result.returncode, 0)
        self.assertEqual(json.loads(result.stdout)["giant"][0]["path"], "a.cs")

    def test_changed_measures_only_those_paths_and_does_not_write(self):
        self.build_world()
        result = self.run_cli(self.root, "--changed", "Shop.Api/Program.cs,Shop.Data/Legacy.cs,bin/Debug/Big.cs", "--json")
        self.assertEqual(result.returncode, 0)
        document = json.loads(result.stdout)
        self.assertEqual(document["totals"]["files"], 2)
        self.assertEqual([item["path"] for item in document["giant"]], ["Shop.Data/Legacy.cs"])
        self.assertFalse(os.path.exists(self.path(code_inventory.INVENTORY_RELATIVE_DIR)))

    def test_writes_the_atomic_json_under_internal(self):
        write(self.path("sub", "Program.cs"), "x\n")
        result = self.run_cli(self.path("sub"), "--root", self.root)
        self.assertEqual(result.returncode, 0)
        target = self.path(code_inventory.INVENTORY_RELATIVE_DIR, "sub.json")
        with open(target, encoding="utf-8") as handle:
            document = json.load(handle)
        self.assertEqual(set(document), {"folder", "generated_at", "totals", "by_extension", "entry_points", "giant", "thresholds"})
        self.assertEqual(document["folder"], "sub")
        self.assertEqual(document["thresholds"]["lines"], 1500)
        self.assertEqual(document["entry_points"], [{"path": "sub/Program.cs", "kind": "startup"}])
        self.assertEqual([name for name in os.listdir(os.path.dirname(target)) if name.endswith(".tmp")], [])

    def test_root_inventory_is_named_root_and_a_folder_without_specs_is_not_written(self):
        write(self.path("a.cs"), "x\n")
        self.run_cli(self.root)
        self.assertTrue(os.path.isfile(self.path(code_inventory.INVENTORY_RELATIVE_DIR, "_root.json")))
        bare = tempfile.mkdtemp(prefix="inventory-bare-")
        self.addCleanup(shutil.rmtree, bare, True)
        write(os.path.join(bare, "a.cs"), "x\n")
        self.assertEqual(self.run_cli(bare).returncode, 0)
        self.assertFalse(os.path.exists(os.path.join(bare, ".specs")))

    def test_harness_forwards_the_inventory_command(self):
        write(self.path("a.cs"), "x\n")
        harness = os.path.join(engine_env.APP_ROOT_DIR, "harness.py")
        result = subprocess.run([sys.executable, harness, "inventory", self.root, "--json", "--no-write"],
                                capture_output=True, text=True, timeout=120)
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(json.loads(result.stdout)["totals"]["files"], 1)


class TestScaleUsesInventory(InventoryTestCase):
    def git(self, *arguments):
        subprocess.run(["git", "-C", self.root, "-c", "user.name=t", "-c", "user.email=t@t"] + list(arguments),
                       capture_output=True, check=True)

    def test_count_code_files_measures_without_an_inventory(self):
        write(self.path("a.cs"), "x\n")
        write(self.path("node_modules", "b.js"), "x\n")
        self.assertEqual(scale.count_code_files(self.root), 1)

    def test_a_fresh_inventory_is_used_and_a_stale_one_is_not(self):
        write(self.path("a.cs"), "x\n")
        write(self.path("b.cs"), "x\n")
        self.git("init", "-q")
        self.git("add", "a.cs", "b.cs")
        self.git("commit", "-q", "-m", "init")
        inventory = self.path(code_inventory.INVENTORY_RELATIVE_DIR, "_root.json")
        write(inventory, json.dumps({"totals": {"files": 99, "lines": 1, "bytes": 1}}))
        now = time.time()
        os.utime(inventory, (now + 100, now + 100))
        self.assertEqual(scale.count_code_files(self.root), 99)
        self.assertEqual(scale.measure(self.root)["code"], 99)
        os.utime(inventory, (now - 100000, now - 100000))
        self.assertEqual(scale.count_code_files(self.root), 2)


