#!/usr/bin/env python3
"""Generates a DRAFT of the "Reuse map" section of the project's CLAUDE.md.

Usage: python map_reuse.py <project-root> [--max 60]
Scans C# (.cs) and TS/TSX/JS looking for what is usually generic and reusable:
  - folders: common, shared, helpers, utils, util, extensions, base, core, lib, hooks, components/ui
  - files/classes: *Helper, *Utils, *Extensions, *Base, Base*, *Factory, *Saver, *Handler, use*.ts(x)
Lists symbol + signature (1 line) + path. Reads nothing beyond that, edits no file, uses no network.
The result is a draft: curate it by hand (one description per line) before pasting into CLAUDE.md.
"""
import os
import re
import sys

SKIP_DIRS = {"node_modules", "bin", "obj", ".git", "dist", "build", ".next", ".specs", ".vs", "coverage", "wwwroot", "Migrations", "__pycache__"}
GENERIC_DIRS = re.compile(r"(^|[\\/])(common|shared|helpers?|utils?|extensions?|base|core|lib|hooks|infrastructure)([\\/]|$)", re.I)
GENERIC_NAMES = re.compile(r"(Helper|Utils?|Extensions?|Base|Factory|Saver|Handler|Formatter|Validator|Mapper)\.(cs|ts|tsx|js)$|^Base\w+\.(cs|ts)$|^use[A-Z]\w+\.(ts|tsx)$")
CS_SYMBOL = re.compile(r"^\s*public\s+(?:static\s+|abstract\s+|virtual\s+|async\s+|sealed\s+|partial\s+)*([\w<>\[\],?\. ]+?)\s+(\w+)\s*\(([^)]*)\)")
CS_TYPE = re.compile(r"^\s*public\s+(?:static\s+|abstract\s+|sealed\s+|partial\s+)*(class|interface|record)\s+(\w+)")
TS_SYMBOL = re.compile(r"^\s*export\s+(?:default\s+)?(?:async\s+)?(function|const|class|interface|type)\s+(\w+)([^{=]*)")


def is_candidate(relative_path, file_name):
    return bool(GENERIC_DIRS.search(os.path.dirname(relative_path) + os.sep) or GENERIC_NAMES.search(file_name))


def symbols_in(path, extension):
    found = []
    try:
        with open(path, encoding="utf-8", errors="replace") as handle:
            for line in handle:
                if extension == ".cs":
                    match = CS_TYPE.match(line)
                    if match:
                        found.append("%s %s" % (match.group(1), match.group(2)))
                        continue
                    match = CS_SYMBOL.match(line)
                    if match and match.group(2) not in ("get", "set"):
                        found.append("%s %s(%s)" % (match.group(1).strip(), match.group(2), " ".join(match.group(3).split())[:70]))
                else:
                    match = TS_SYMBOL.match(line)
                    if match:
                        found.append("%s %s%s" % (match.group(1), match.group(2), " ".join(match.group(3).split())[:70]))
                if len(found) >= 8:
                    break
    except OSError:
        pass
    return found


def main():
    args = sys.argv[1:]
    if not args:
        print(__doc__)
        return 2
    root = os.path.abspath(args[0])
    limit = int(args[args.index("--max") + 1]) if "--max" in args else 60
    rows = []
    for current, dirs, files in os.walk(root):
        dirs[:] = [name for name in dirs if name not in SKIP_DIRS]
        for file_name in files:
            extension = os.path.splitext(file_name)[1]
            if extension not in (".cs", ".ts", ".tsx", ".js"):
                continue
            if file_name.endswith((".d.ts", ".test.ts", ".test.tsx", ".spec.ts", ".Designer.cs")):
                continue
            full = os.path.join(current, file_name)
            relative = os.path.relpath(full, root).replace("\\", "/")
            if is_candidate(relative, file_name):
                symbols = symbols_in(full, extension)
                if symbols:
                    rows.append((relative, symbols))
    rows.sort()
    print("## Reuse map (DRAFT generated by map_reuse.py; curate by hand)")
    print()
    print("| I need... | Use | Where | Signature / note |")
    print("|---|---|---|---|")
    for relative, symbols in rows[:limit]:
        for symbol in symbols[:3]:
            name = re.sub(r"^(class|interface|record|function|const|type)\s+", "", symbol).split("(")[0].split()[-1]
            print("| <describe the need> | `%s` | `%s` | %s |" % (name, relative, symbol.replace("|", "/")))
    if len(rows) > limit:
        print()
        print("<!-- %d candidate files beyond the %d listed; use --max -->" % (len(rows) - limit, limit))
    if not rows:
        print("| (no generic helper detected) | | | |")
    print()
    print("## Structure (draft: top-level folders)")
    print()
    print("| Folder | What it holds | Accepts new code? |")
    print("|---|---|---|")
    for name in sorted(os.listdir(root)):
        if os.path.isdir(os.path.join(root, name)) and name not in SKIP_DIRS and not name.startswith("."):
            print("| `%s/` | <describe> | <yes/no> |" % name)
    return 0


if __name__ == "__main__":
    sys.exit(main())
